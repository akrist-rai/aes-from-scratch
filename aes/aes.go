// Package aes implements AES (Advanced Encryption Standard) from scratch.
// Supports AES-128, AES-192, and AES-256 (FIPS 197).
package aes

import "errors"

// Number of rounds per key size.
const (
	rounds128 = 10
	rounds192 = 12
	rounds256 = 14
)

// BlockSize is the AES block size in bytes (always 128 bits).
const BlockSize = 16

// Cipher holds expanded round keys.
type Cipher struct {
	keys   [][][4]byte // [round][col][byte] — same keys used for enc and dec
	rounds int
}

// NewCipher creates a new AES cipher from a 16, 24, or 32 byte key.
func NewCipher(key []byte) (*Cipher, error) {
	switch len(key) {
	case 16, 24, 32:
	default:
		return nil, errors.New("aes: key must be 16, 24, or 32 bytes")
	}
	c := &Cipher{}
	c.keys = keyExpansion(key)
	c.rounds = len(c.keys) - 1
	return c, nil
}

// Encrypt encrypts a single 16-byte block in place.
func (c *Cipher) Encrypt(block []byte) error {
	if len(block) != BlockSize {
		return errors.New("aes: block must be 16 bytes")
	}
	s := bytesToState(block)
	s = encryptState(s, c.keys, c.rounds)
	stateToBytes(s, block)
	return nil
}

// Decrypt decrypts a single 16-byte block in place.
func (c *Cipher) Decrypt(block []byte) error {
	if len(block) != BlockSize {
		return errors.New("aes: block must be 16 bytes")
	}
	s := bytesToState(block)
	s = decryptState(s, c.keys, c.rounds)
	stateToBytes(s, block)
	return nil
}

// ─── State helpers ────────────────────────────────────────────────────────────

// AES state is a 4×4 byte matrix stored column-major.
type state [4][4]byte

func bytesToState(b []byte) state {
	var s state
	for col := 0; col < 4; col++ {
		for row := 0; row < 4; row++ {
			s[row][col] = b[col*4+row]
		}
	}
	return s
}

func stateToBytes(s state, b []byte) {
	for col := 0; col < 4; col++ {
		for row := 0; row < 4; row++ {
			b[col*4+row] = s[row][col]
		}
	}
}

// ─── Encryption ───────────────────────────────────────────────────────────────

func encryptState(s state, keys [][][4]byte, rounds int) state {
	s = addRoundKey(s, keys[0])
	for r := 1; r < rounds; r++ {
		s = subBytes(s)
		s = shiftRows(s)
		s = mixColumns(s)
		s = addRoundKey(s, keys[r])
	}
	// Final round — no MixColumns.
	s = subBytes(s)
	s = shiftRows(s)
	s = addRoundKey(s, keys[rounds])
	return s
}

// ─── Decryption ───────────────────────────────────────────────────────────────

func decryptState(s state, keys [][][4]byte, rounds int) state {
	s = addRoundKey(s, keys[rounds])
	for r := rounds - 1; r >= 1; r-- {
		s = invShiftRows(s)
		s = invSubBytes(s)
		s = addRoundKey(s, keys[r])
		s = invMixColumns(s)
	}
	s = invShiftRows(s)
	s = invSubBytes(s)
	s = addRoundKey(s, keys[0])
	return s
}

// ─── AddRoundKey ──────────────────────────────────────────────────────────────

func addRoundKey(s state, roundKey [][4]byte) state {
	for col := 0; col < 4; col++ {
		for row := 0; row < 4; row++ {
			s[row][col] ^= roundKey[col][row]
		}
	}
	return s
}

// ─── SubBytes / InvSubBytes ───────────────────────────────────────────────────

func subBytes(s state) state {
	for row := 0; row < 4; row++ {
		for col := 0; col < 4; col++ {
			s[row][col] = sbox[s[row][col]]
		}
	}
	return s
}

func invSubBytes(s state) state {
	for row := 0; row < 4; row++ {
		for col := 0; col < 4; col++ {
			s[row][col] = sboxInv[s[row][col]]
		}
	}
	return s
}

// ─── ShiftRows / InvShiftRows ─────────────────────────────────────────────────

// Row i is rotated left by i positions.
func shiftRows(s state) state {
	s[1][0], s[1][1], s[1][2], s[1][3] = s[1][1], s[1][2], s[1][3], s[1][0]
	s[2][0], s[2][1], s[2][2], s[2][3] = s[2][2], s[2][3], s[2][0], s[2][1]
	s[3][0], s[3][1], s[3][2], s[3][3] = s[3][3], s[3][0], s[3][1], s[3][2]
	return s
}

// Row i is rotated right by i positions.
func invShiftRows(s state) state {
	s[1][0], s[1][1], s[1][2], s[1][3] = s[1][3], s[1][0], s[1][1], s[1][2]
	s[2][0], s[2][1], s[2][2], s[2][3] = s[2][2], s[2][3], s[2][0], s[2][1]
	s[3][0], s[3][1], s[3][2], s[3][3] = s[3][1], s[3][2], s[3][3], s[3][0]
	return s
}

// ─── MixColumns / InvMixColumns ───────────────────────────────────────────────

// xtime multiplies a byte by 2 in GF(2^8) with reduction polynomial x^8+x^4+x^3+x+1.
func xtime(b byte) byte {
	if b&0x80 != 0 {
		return (b << 1) ^ 0x1b
	}
	return b << 1
}

// gmul multiplies two bytes in GF(2^8) using the Russian peasant algorithm.
func gmul(a, b byte) byte {
	var p byte
	for i := 0; i < 8; i++ {
		if b&1 != 0 {
			p ^= a
		}
		a = xtime(a)
		b >>= 1
	}
	return p
}

func mixColumns(s state) state {
	for col := 0; col < 4; col++ {
		a := s[0][col]
		b := s[1][col]
		c := s[2][col]
		d := s[3][col]
		s[0][col] = gmul(2, a) ^ gmul(3, b) ^ c ^ d
		s[1][col] = a ^ gmul(2, b) ^ gmul(3, c) ^ d
		s[2][col] = a ^ b ^ gmul(2, c) ^ gmul(3, d)
		s[3][col] = gmul(3, a) ^ b ^ c ^ gmul(2, d)
	}
	return s
}

func invMixColumns(s state) state {
	for col := 0; col < 4; col++ {
		a := s[0][col]
		b := s[1][col]
		c := s[2][col]
		d := s[3][col]
		s[0][col] = gmul(0x0e, a) ^ gmul(0x0b, b) ^ gmul(0x0d, c) ^ gmul(0x09, d)
		s[1][col] = gmul(0x09, a) ^ gmul(0x0e, b) ^ gmul(0x0b, c) ^ gmul(0x0d, d)
		s[2][col] = gmul(0x0d, a) ^ gmul(0x09, b) ^ gmul(0x0e, c) ^ gmul(0x0b, d)
		s[3][col] = gmul(0x0b, a) ^ gmul(0x0d, b) ^ gmul(0x09, c) ^ gmul(0x0e, d)
	}
	return s
}

// ─── Key Expansion ────────────────────────────────────────────────────────────

// subWord applies sbox to each byte of a 4-byte word.
func subWord(w [4]byte) [4]byte {
	return [4]byte{sbox[w[0]], sbox[w[1]], sbox[w[2]], sbox[w[3]]}
}

// rotWord rotates a 4-byte word left by one byte.
func rotWord(w [4]byte) [4]byte {
	return [4]byte{w[1], w[2], w[3], w[0]}
}

// keyExpansion produces (rounds+1) round keys, each 4 words wide.
func keyExpansion(key []byte) [][][4]byte {
	nk := len(key) / 4 // words in key: 4, 6, or 8
	var nr int
	switch nk {
	case 4:
		nr = rounds128
	case 6:
		nr = rounds192
	case 8:
		nr = rounds256
	}

	totalWords := 4 * (nr + 1)
	w := make([][4]byte, totalWords)

	// Copy key into first nk words.
	for i := 0; i < nk; i++ {
		w[i] = [4]byte{key[4*i], key[4*i+1], key[4*i+2], key[4*i+3]}
	}

	for i := nk; i < totalWords; i++ {
		tmp := w[i-1]
		if i%nk == 0 {
			tmp = subWord(rotWord(tmp))
			tmp[0] ^= rcon[i/nk-1]
		} else if nk > 6 && i%nk == 4 {
			tmp = subWord(tmp)
		}
		w[i] = xorWords(w[i-nk], tmp)
	}

	// Package into rounds: each round key is 4 words.
	keys := make([][][4]byte, nr+1)
	for r := 0; r <= nr; r++ {
		keys[r] = w[r*4 : r*4+4]
	}
	return keys
}

func xorWords(a, b [4]byte) [4]byte {
	return [4]byte{a[0] ^ b[0], a[1] ^ b[1], a[2] ^ b[2], a[3] ^ b[3]}
}

